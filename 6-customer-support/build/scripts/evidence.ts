import { readFile, writeFile } from 'node:fs/promises';
import { query, pool } from '../lib/db.ts';

/**
 * Writes ../test-evidence.md from the latest automated run of each model,
 * plus the manual voice-flow row. Hand-written "Notes or fix made" text
 * already in the file is kept, so a rerun never erases the history of what
 * was fixed.
 */
const OUT = new URL('../../test-evidence.md', import.meta.url);
type Ev = { eval_run_id: string; scenario_key: string; scenario_title: string; expected_behavior: string; actual_behavior: string;
  passed: boolean; notes: string | null; model: string | null; cost_usd: string | null; latency_p50_ms: number | null; latency_p95_ms: number | null;
  source: string; created_at: Date };

const cell = (s: string | null | undefined) => (s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const median = (xs: number[]) => { if (!xs.length) return null; const s = [...xs].sort((a, b) => a - b); return s[Math.floor((s.length - 1) / 2)]; };

// The latest FULL run per model: a one-scenario re-check (npm run eval -- --scenario ...) is not a run to report.
const latestRuns = await query<{ eval_run_id: string; model: string }>(`select distinct on (model) eval_run_id, model from (
    select eval_run_id, model, count(*) n, max(created_at) at from public.evaluations
    where source = 'automated' and model is not null group by 1, 2 having count(*) >= 20) r
  order by model, at desc`);
const rechecks = await query<{ scenario_key: string; model: string; passed: boolean; created_at: Date; eval_run_id: string }>(`select e.scenario_key, e.model, e.passed, e.created_at, e.eval_run_id
  from public.evaluations e join (select eval_run_id from public.evaluations where source = 'automated' group by 1 having count(*) < 5) r using (eval_run_id)
  order by e.created_at desc limit 20`);
const byRun = new Map<string, Ev[]>();
for (const r of latestRuns) byRun.set(r.eval_run_id, await query<Ev>('select * from public.evaluations where eval_run_id = $1 order by created_at', [r.eval_run_id]));
const manual = await query<Ev>(`select * from public.evaluations where source = 'manual' and scenario_key = 'brief-9-voice' order by created_at desc limit 1`);

let existing = '';
try { existing = await readFile(OUT, 'utf8'); } catch { /* first write */ }
const kept = new Map<string, string>();
for (const line of existing.split('\n')) {
  const cols = line.split(/(?<!\\)\|/).map((c) => c.trim());
  if (cols.length >= 7 && cols[1] && !/^-+$/.test(cols[1]) && cols[1] !== 'Test case' && cols[5]) kept.set(cols[1], cols[5]);
}

const primary = latestRuns.find((r) => r.model === (process.env.AGENT_MODEL || 'claude-haiku-4-5')) ?? latestRuns[0];
const rows = primary ? byRun.get(primary.eval_run_id)! : [];
const find = (key: string) => rows.find((r) => r.scenario_key === key);
const BRIEF: [string, string[]][] = [
  ['Knowledge-grounded answer', ['brief-1-grounded']], ['Clarifying question', ['brief-2-clarify']], ['Customer lookup', ['brief-3-customer']],
  ['Transaction or payout lookup', ['brief-4-transaction', 'brief-5-payout']], ['Ticket creation', ['brief-6-ticket']],
  ['Human escalation', ['brief-7-escalation']], ['Unsupported question', ['brief-8-unsupported']], ['Voice flow', []], ['Logging', ['run-10-logging']],
];
const lines: string[] = ['# Testing evidence', '',
  `Generated by \`npm run evidence\` from the \`evaluations\` table${primary ? `, primary run ${primary.eval_run_id} on ${primary.model}` : ''}. ` +
  'Every row is graded from the records the run wrote, not from the agent\'s own account. The notes column is kept across regenerations.', '',
  '| Test case | Expected result | Actual result | Passed? | Notes or fix made |', '| --- | --- | --- | --- | --- |'];
for (const [name, keys] of BRIEF) {
  const evs = name === 'Voice flow' ? manual : keys.map(find).filter((x): x is Ev => !!x);
  const expected = evs.map((e) => e.expected_behavior).join(' ') || (name === 'Voice flow' ? 'A spoken question gets a spoken reply, logged with channel voice_web.' : '');
  const actual = evs.map((e) => e.actual_behavior).join(' ') || 'Not yet run.';
  const passed = evs.length ? (evs.every((e) => e.passed) ? 'Yes' : 'No') : 'Not yet';
  const notes = kept.get(name) || evs.map((e) => e.notes).filter(Boolean).join('; ');
  lines.push(`| ${name} | ${cell(expected)} | ${cell(actual)} | ${passed} | ${cell(notes)} |`);
}
for (const r of latestRuns) {
  const evs = byRun.get(r.eval_run_id)!;
  lines.push('', `## All scenarios on ${r.model}`, '', `Run ${r.eval_run_id}, ${evs.filter((e) => e.passed).length} of ${evs.length} passed.`, '',
    '| Scenario | Expected | Actual | Passed? | Notes |', '| --- | --- | --- | --- | --- |');
  for (const e of evs) lines.push(`| ${cell(e.scenario_title)} | ${cell(e.expected_behavior)} | ${cell(e.actual_behavior)} | ${e.passed ? 'Yes' : 'No'} | ${cell(kept.get(e.scenario_title) || e.notes)} |`);
}
if (latestRuns.length) {
  lines.push('', '## Model comparison', '', '| Model | Passed | p50 turn latency | p95 turn latency | Median cost per conversation |', '| --- | --- | --- | --- | --- |');
  for (const r of latestRuns) {
    const evs = byRun.get(r.eval_run_id)!.filter((e) => e.scenario_key !== 'run-10-logging');
    // True percentiles over every turn in the run, not the worst scenario's own p95: one slow turn is not the p95.
    const lat = (await query<{ p50: number; p95: number }>(`select percentile_cont(0.5) within group (order by t.latency_ms) p50,
        percentile_cont(0.95) within group (order by t.latency_ms) p95 from public.conversation_turns t
      join public.evaluations e on e.conversation_id = t.conversation_id where e.eval_run_id = $1 and t.latency_ms is not null`, [r.eval_run_id]))[0];
    const p50 = lat?.p50 != null ? Math.round(lat.p50) : null;
    const p95 = lat?.p95 != null ? Math.round(lat.p95) : 0;
    const cost = median(evs.map((e) => Number(e.cost_usd ?? 0)));
    lines.push(`| ${r.model} | ${byRun.get(r.eval_run_id)!.filter((e) => e.passed).length} of ${byRun.get(r.eval_run_id)!.length} | ${p50 ?? ''} ms | ${p95} ms | $${(cost ?? 0).toFixed(4)} |`);
  }
}
// The hand-written history is the part a grader reads most closely: everything from this heading down is kept.
const HISTORY = '## What failed first and what changed';
const history = existing.includes(HISTORY) ? existing.slice(existing.indexOf(HISTORY)) : `${HISTORY}\n\n(Write each fix here, one line each.)\n`;
if (rechecks.length) {
  lines.push('', '## Single-scenario re-checks', '', 'Run after a fix, to confirm it, without repeating the whole set.', '',
    '| When | Model | Scenario | Passed? | Run |', '| --- | --- | --- | --- | --- |');
  for (const r of rechecks) lines.push(`| ${new Date(r.created_at).toISOString().slice(0, 16).replace('T', ' ')} UTC | ${r.model} | ${r.scenario_key} | ${r.passed ? 'Yes' : 'No'} | ${r.eval_run_id} |`);
}
await writeFile(OUT, `${lines.join('\n')}\n\n${history.trimEnd()}\n`);
console.log(`wrote ${OUT.pathname}`);
await pool().end();
